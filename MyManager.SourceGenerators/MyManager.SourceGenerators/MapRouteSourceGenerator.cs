using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace MyManager.SourceGenerators;

[Generator]
public sealed class MapRouteSourceGenerator : IIncrementalGenerator
{
    private const string Namespace = "MyManager.Routing.Attributes";
    private const string AttributeName = "MapRouteAttribute";

    private readonly struct EndpointModel(
        MethodDeclarationSyntax syntax,
        AttributeData attributeData
    )
    {
        public MethodDeclarationSyntax Syntax { get; } = syntax;
        public AttributeData AttributeData { get; } = attributeData;
    }

    private static IncrementalValuesProvider<EndpointModel> GetRouteProvider(
        IncrementalGeneratorInitializationContext context,
        string attributeName)
    {
        return context.SyntaxProvider.ForAttributeWithMetadataName(
            attributeName,
            predicate: static (node, _) => node is MethodDeclarationSyntax,
            transform: static (ctx, _) =>
            {
                var syntax = (MethodDeclarationSyntax)ctx.TargetNode;
                var attributeData = ctx.Attributes[0];
                return new EndpointModel(syntax, attributeData);
            });
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var mapGetProvider = GetRouteProvider(context, $"{Namespace}.MapGetAttribute");
        var mapPostProvider = GetRouteProvider(context, $"{Namespace}.MapPostAttribute");
        var mapPutProvider = GetRouteProvider(context, $"{Namespace}.MapPutAttribute");
        var mapDeleteProvider = GetRouteProvider(context, $"{Namespace}.MapDeleteAttribute");
        var mapPatchProvider = GetRouteProvider(context, $"{Namespace}.MapPatchAttribute");


        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapGetProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Get", sourceProductionContext, t));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapPostProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Post", sourceProductionContext, t));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapPutProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Put", sourceProductionContext, t));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapDeleteProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Delete", sourceProductionContext, t));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapPatchProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Patch", sourceProductionContext, t));

        const string code =
            """
            // <auto-generated/>

            namespace MyManager.Routing;

            public static partial class Routes
            {
                public static void RegisterRoutes(this IEndpointRouteBuilder app)
                {
                    RegisterGetRoutes(app);
                    RegisterPostRoutes(app);
                    RegisterPutRoutes(app);
                    RegisterDeleteRoutes(app);
                    RegisterPatchRoutes(app);
                }
            }
            """;

        context.RegisterPostInitializationOutput(ctx =>
        {
            ctx.AddSource("Routes.g.cs", SourceText.From(code, Encoding.UTF8));
        });
    }

    private static void GenerateRouteConfiguration(
        string prefix,
        SourceProductionContext sourceProductionContext,
        (Compilation compilation, ImmutableArray<EndpointModel> endpointModels) t)
    {
        var (compilation, endpointModels) = t;

        var sb = new StringBuilder();

        sb.AppendLine($"// <auto-generated/>");
        sb.AppendLine();
        sb.AppendLine("namespace MyManager.Routing;");
        sb.AppendLine();

        sb.AppendLine($"public static partial class Routes");
        sb.AppendLine("{");
        sb.AppendLine($"    private static void Register{prefix}Routes(this IEndpointRouteBuilder app)");
        sb.AppendLine("    {");

        foreach (var model in endpointModels)
        {
            var syntax = model.Syntax;
            var attributeName = model.AttributeData.AttributeClass?.Name;
            if (attributeName is null) continue;

            if (compilation.GetSemanticModel(syntax.SyntaxTree).GetDeclaredSymbol(syntax) is not { } symbol)
                continue;

            var otherAttributes = symbol.GetAttributes();

            var args = model.AttributeData.ConstructorArguments;

            if (args.ElementAt(0).Value is not string pattern) continue;

            var verb = attributeName.Replace("Attribute", "");

            var methodName = symbol.Name;
            var namespaceName = symbol.ContainingType?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            sb.AppendLine($"        app");
            sb.AppendLine($"            .{verb}(\"{pattern}\", {namespaceName}.{methodName})");

            foreach (var a in otherAttributes)
            {
                if (a.AttributeClass is null) continue;

                var displayString = a.AttributeClass.ToDisplayString();

                // sb.AppendLine("// " + displayString);

                if (displayString == "MyManager.Routing.Attributes.WithNameAttribute")
                {
                    var value = a.ConstructorArguments.ElementAt(0).Value as string;
                    sb.AppendLine($"            .WithName(\"{value}\")");
                }
                else if (displayString == "MyManager.Routing.Attributes.WithDisplayNameAttribute")
                {
                    var value = a.ConstructorArguments.ElementAt(0).Value as string;
                    sb.AppendLine($"            .WithDisplayName(\"{value}\")");
                }
                else if (displayString == "MyManager.Routing.Attributes.WithDescriptionAttribute")
                {
                    var value = a.ConstructorArguments.ElementAt(0).Value as string;
                    sb.AppendLine($"            .WithDescription(\"{value}\")");
                }
                else if (displayString == "MyManager.Routing.Attributes.WithOrderAttribute")
                {
                    var value = a.ConstructorArguments.ElementAt(0).Value as string;
                    sb.AppendLine($"            .WithOrder({value})");
                }
                else if (displayString == "MyManager.Routing.Attributes.WithSummaryAttribute")
                {
                    var value = a.ConstructorArguments.ElementAt(0).Value as string;
                    sb.AppendLine($"            .WithSummary(\"{value}\")");
                }
                else if (displayString == "MyManager.Routing.Attributes.WithGroupNameAttribute")
                {
                    var value = a.ConstructorArguments.ElementAt(0).Value as string;
                    sb.AppendLine($"            .WithGroupName(\"{value}\")");
                }
                else if (displayString == "MyManager.Routing.Attributes.WithTagsAttribute")
                {
                    var values = a.ConstructorArguments.ElementAt(0).Values.Select(x => $"\"{x.Value as string}\"");
                    sb.AppendLine($"            .WithTags({string.Join(", ", values)})");
                }
                else if (displayString == "MyManager.Routing.Attributes.AllowAnonymousAttribute")
                {
                    sb.AppendLine($"            .AllowAnonymous()");
                }
                else if (displayString.Contains("MyManager.Routing.Attributes.AddEndpointFilterAttribute"))
                {
                    var value = a.AttributeClass.TypeParameters.First().ToDisplayString();
                    sb.AppendLine($"            .AddEndpointFilter<{value}>()");
                }
                else if (displayString.Contains("MyManager.Routing.Attributes.ProducesAttribute"))
                {
                    var value = a.ConstructorArguments.ElementAt(0).Value as string;

                    if (!a.AttributeClass.IsGenericType)
                        sb.AppendLine($"            .Produces({value})");
                    else
                    {
                        var type = a.AttributeClass.TypeArguments.First().ToDisplayString();
                        sb.AppendLine($"            .Produces<{type}>({value})");
                    }
                }
            }

            sb.AppendLine("        ;\n");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        sourceProductionContext.AddSource($"Routes.{prefix}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}
