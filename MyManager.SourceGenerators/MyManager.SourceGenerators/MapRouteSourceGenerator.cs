using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace MyManager.SourceGenerators;

[Generator]
public sealed class MapRouteSourceGenerator : IIncrementalGenerator
{
    private const string Namespace = "MyManager.Attributes";
    private const string AttributeName = "MapRouteAttribute";
    private const string AttributeDisplayName = $"{Namespace}.{AttributeName}";

    private readonly struct EndpointModel(
        MethodDeclarationSyntax syntax,
        AttributeData attributeData
    )
    {
        public MethodDeclarationSyntax Syntax { get; } = syntax;
        public AttributeData AttributeData { get; } = attributeData;
    }

    private static IncrementalValuesProvider<EndpointModel> GetRouteProvider(
        IncrementalGeneratorInitializationContext context,
        string attributeName)
    {
        return context.SyntaxProvider.ForAttributeWithMetadataName(
            attributeName,
            predicate: static (node, _) => node is MethodDeclarationSyntax,
            transform: static (ctx, _) =>
            {
                var syntax = (MethodDeclarationSyntax)ctx.TargetNode;
                var attributeData = ctx.Attributes[0];
                return new EndpointModel(syntax, attributeData);
            });
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var mapGetProvider = GetRouteProvider(context, $"{Namespace}.MapGetAttribute");
        var mapPostProvider = GetRouteProvider(context, $"{Namespace}.MapPostAttribute");
        var mapPutProvider = GetRouteProvider(context, $"{Namespace}.MapPutAttribute");
        var mapDeleteProvider = GetRouteProvider(context, $"{Namespace}.MapDeleteAttribute");

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapGetProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Get", sourceProductionContext, t));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapPostProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Post", sourceProductionContext, t));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapPutProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Put", sourceProductionContext, t));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(mapDeleteProvider.Collect()),
            (sourceProductionContext, t) => GenerateRouteConfiguration("Delete", sourceProductionContext, t));

        const string code = $$"""
                              // <auto-generated/>
                              
                              namespace MyManager;

                              public static partial class Routes
                              {
                                  public static void RegisterRoutes(this IEndpointRouteBuilder app)
                                  {
                                      RegisterGetRoutes(app);
                                      RegisterPostRoutes(app);
                                      RegisterPutRoutes(app);
                                      RegisterDeleteRoutes(app);
                                  }
                              }
                              """;

        context.RegisterPostInitializationOutput(
            context =>
            {
                context.AddSource("Routes.g.cs", SourceText.From(code, Encoding.UTF8));
            });
    }

    private static void GenerateRouteConfiguration(
        string prefix,
        SourceProductionContext sourceProductionContext,
        (Compilation compilation, ImmutableArray<EndpointModel> endpointModels) t)
    {
        var (compilation, endpointModels) = t;

        var sb = new StringBuilder();

        sb.AppendLine($"// <auto-generated/>");
        sb.AppendLine();
        sb.AppendLine("namespace MyManager;");
        sb.AppendLine();

        sb.AppendLine($"public static partial class Routes");
        sb.AppendLine("{");
        sb.AppendLine($"    private static void Register{prefix}Routes(this IEndpointRouteBuilder app)");
        sb.AppendLine("    {");

        foreach (var model in endpointModels)
        {
            var syntax = model.Syntax;
            var attributeName = model.AttributeData.AttributeClass?.Name;
            if (attributeName is null) continue;

            if (compilation.GetSemanticModel(syntax.SyntaxTree).GetDeclaredSymbol(syntax) is not IMethodSymbol symbol) continue;

            var args = model.AttributeData.ConstructorArguments;

            if (args.ElementAt(0).Value is not string pattern) continue;

            var name = args.ElementAt(1).Value as string;

            var verb = attributeName.Replace("Attribute", "");

            var methodName = symbol.Name;
            var namespaceName = symbol.ContainingType?.ToDisplayString();

            var handler = compilation.GetSemanticModel(syntax.SyntaxTree);
            sb.Append($"        app.{verb}(\"{pattern}\", {namespaceName}.{methodName})");
            if (name is not null) sb.Append($".WithName(\"{name}\")");
            sb.AppendLine(";");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        sourceProductionContext.AddSource($"Routes.{prefix}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}
